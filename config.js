function nthWeekday(date){
  return Math.ceil(date.getDate()/7);
}

function garbageFor(date){
  const day=date.getDay();
  const nth=nthWeekday(date);

  if(day===2 || day===5) return "燃やすごみ";
  if(day===4) return "プラスチック";
  if(day===6) return "資源";
  if(day===3 && (nth===1 || nth===3)) return "燃やさないごみ";

  return "収集なし";
}
